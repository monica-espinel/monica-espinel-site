#!/usr/bin/env python3
"""Generate static redirect pages for old WordPress URLs (GitHub Pages has no server redirects).

Usage: python3 -I scripts/make_redirects.py [--types feed,pagination,...]

Reads migration/url-inventory.csv and writes static/<old_url>/index.html for each row whose
action is `redirect`, plus feed rows marked `alias` (Hugo aliases can only point at pages,
not at index.xml feeds). Each page has a canonical link, a meta refresh, a visible link
and `noindex`. Rows Hugo already handles (`keep`, page aliases) are skipped.

--types limits the run to some row types (Phase 3 generates feeds only; Phase 4 the rest).
Pages this script wrote before but no longer produces are deleted (they carry a marker).
"""
import csv
import html
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "migration" / "url-inventory.csv"
STATIC = ROOT / "static"
SITE = "https://monicaespinel.com"
MARKER = "<!-- generated by scripts/make_redirects.py -->"

TEMPLATE = """<!DOCTYPE html>
<html lang="en-US">
<head>
{marker}
<meta charset="utf-8">
<title>{title}</title>
<link rel="canonical" href="{url}">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url={url}">
</head>
<body>
<p>This page has moved to <a href="{url}">{url}</a>.</p>
</body>
</html>
"""


def wanted(row, types):
    if types and row["type"] not in types:
        return False
    if row["action"] == "redirect":
        return True
    # Feed aliases point at index.xml files, which Hugo aliases can't do.
    return row["action"] == "alias" and row["type"] == "feed"


def main(argv):
    types = set()
    if "--types" in argv:
        types = set(argv[argv.index("--types") + 1].split(","))
    rows = [r for r in csv.DictReader(INVENTORY.open(encoding="utf-8")) if wanted(r, types)]

    written = set()
    for r in rows:
        old = r["old_url"]
        if "?" in old or not old.endswith("/"):
            sys.exit(f"cannot make a static page for {old}")
        dest = STATIC / old.strip("/") / "index.html"
        url = SITE + r["target"]
        title = html.escape(r["title"] or "Moved", quote=False)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(TEMPLATE.format(marker=MARKER, title=title, url=html.escape(url)), encoding="utf-8")
        written.add(dest)

    # Remove pages generated earlier (for the same types) that are no longer wanted.
    removed = 0
    for f in STATIC.rglob("index.html"):
        if f in written or MARKER not in f.read_text(encoding="utf-8", errors="replace")[:400]:
            continue
        if types:
            # Only clean up pages of the types handled in this run.
            rel = "/" + f.parent.relative_to(STATIC).as_posix() + "/"
            row_types = {r["type"] for r in csv.DictReader(INVENTORY.open(encoding="utf-8")) if r["old_url"] == rel}
            if row_types and not row_types & types:
                continue
        f.unlink()
        removed += 1
        for d in f.parents:
            if d == STATIC or any(d.iterdir()):
                break
            d.rmdir()
    print(f"{len(written)} redirect pages written under static/" + (f", {removed} stale removed" if removed else ""))


if __name__ == "__main__":
    main(sys.argv[1:])

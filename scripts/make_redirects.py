#!/usr/bin/env python3
"""Generate static redirect pages for old WordPress URLs (GitHub Pages has no server redirects).

Usage: python3 -I scripts/make_redirects.py [--types feed,pagination,...]

Reads migration/url-inventory.csv and writes static/<old_url>/index.html for each row whose
action is `redirect`, plus feed rows marked `alias` (Hugo aliases can only point at pages,
not at index.xml feeds). Each page has a canonical link, a meta refresh, a visible link
and `noindex`. Rows Hugo already handles (`keep`, page aliases) are skipped.

--types limits the run to some row types (Phase 3 generates feeds only; Phase 4 the rest).
Pages this script wrote before but no longer produces are deleted (they carry a marker).
"""
import csv
import html
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "migration" / "url-inventory.csv"
STATIC = ROOT / "static"
SITE = "https://monicaespinel.com"
MARKER = "<!-- generated by scripts/make_redirects.py -->"

# One redirect page template for the whole site: Hugo's alias template (layouts/alias.html),
# whose only variable is {{ .Permalink }}, the target URL.
ALIAS_TEMPLATE = ROOT / "layouts" / "alias.html"


def render(url):
    page = ALIAS_TEMPLATE.read_text(encoding="utf-8")
    if "{{" in page.replace("{{ .Permalink }}", ""):
        sys.exit(f"{ALIAS_TEMPLATE} uses template features other than {{{{ .Permalink }}}}")
    page = page.replace("{{ .Permalink }}", html.escape(url))
    return page.replace("<head>", "<head>\n  " + MARKER, 1)


def wanted(row, types):
    if types and row["type"] not in types:
        return False
    if row["action"] == "redirect":
        return True
    # Feed aliases point at index.xml files, which Hugo aliases can't do.
    return row["action"] == "alias" and row["type"] == "feed"


def main(argv):
    types = set()
    if "--types" in argv:
        types = set(argv[argv.index("--types") + 1].split(","))
    with INVENTORY.open(encoding="utf-8") as f:
        inventory = list(csv.DictReader(f))
    type_of = {r["old_url"]: r["type"] for r in inventory}
    rows = [r for r in inventory if wanted(r, types)]

    # Paths Hugo renders itself (kept pages, and Hugo aliases for old post slugs).
    # A redirect page there would collide with Hugo's output, so refuse it.
    hugo_paths = {r["old_url"] for r in inventory
                  if r["action"] == "keep" or (r["action"] == "alias" and r["type"] != "feed")}
    clash = sorted(r["old_url"] for r in rows if r["old_url"] in hugo_paths)
    if clash:
        sys.exit("redirect pages would collide with pages Hugo renders: " + ", ".join(clash))

    written = set()
    for r in rows:
        old = r["old_url"]
        if "?" in old or not old.endswith("/"):
            sys.exit(f"cannot make a static page for {old}")
        dest = STATIC / old.strip("/") / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(render(SITE + r["target"]), encoding="utf-8")
        written.add(dest)

    # Remove pages generated earlier (for the same types) that are no longer wanted.
    removed = 0
    for f in STATIC.rglob("index.html"):
        if f in written or MARKER not in f.read_text(encoding="utf-8", errors="replace")[:400]:
            continue
        if types:
            # Only clean up pages of the types handled in this run.
            row_type = type_of.get("/" + f.parent.relative_to(STATIC).as_posix() + "/")
            if row_type and row_type not in types:
                continue
        f.unlink()
        removed += 1
        for d in f.parents:
            if d == STATIC or any(d.iterdir()):
                break
            d.rmdir()
    print(f"{len(written)} redirect pages written under static/" + (f", {removed} stale removed" if removed else ""))


if __name__ == "__main__":
    main(sys.argv[1:])

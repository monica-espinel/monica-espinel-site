#!/usr/bin/env python3
"""Generate static redirect pages for old WordPress URLs (GitHub Pages has no server redirects).

Usage: python3 -I scripts/make_redirects.py [--types feed,pagination,...] [--check]

Reads migration/url-inventory.csv and writes static/<old_url>/index.html for each row whose
action is `redirect`, plus feed rows marked `alias` (Hugo aliases can only point at pages,
not at index.xml feeds). Each page comes from Hugo's own alias template (layouts/alias.html):
an absolute canonical link, a root-relative meta refresh and visible link (so redirects work
on any host, including previews), and `noindex`. Rows Hugo handles itself are skipped.

--types  limits the run to some row types (Phase 3 generated feeds only; Phase 4 the rest).
--check  writes nothing: exits 1 if the committed pages differ from what the inventory gives
         (missing, changed or stale pages). The deploy workflow runs this.
Pages this script wrote before but no longer produces are deleted (they carry a marker).
"""
import csv
import html
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "migration" / "url-inventory.csv"
STATIC = ROOT / "static"
CONTENT = ROOT / "content"
# The site origin comes from hugo.toml, so redirect pages and Hugo's pages always agree.
SITE = tomllib.loads((ROOT / "hugo.toml").read_text(encoding="utf-8"))["baseURL"].rstrip("/")
MARKER = "<!-- generated by scripts/make_redirects.py -->"

# One redirect page template for the whole site: Hugo's alias template (layouts/alias.html).
# Its only variables are {{ .Permalink }} (absolute target) and {{ .Page.RelPermalink }} (root-relative).
ALIAS_TEMPLATE = ROOT / "layouts" / "alias.html"
PLACEHOLDERS = ("{{ .Permalink }}", "{{ .Page.RelPermalink }}")


def render(target):
    page = ALIAS_TEMPLATE.read_text(encoding="utf-8")
    rest = page
    for p in PLACEHOLDERS:
        rest = rest.replace(p, "")
    if "{{" in rest:
        sys.exit(f"{ALIAS_TEMPLATE} uses template features other than {', '.join(PLACEHOLDERS)}")
    page = page.replace(PLACEHOLDERS[0], html.escape(SITE + target)).replace(PLACEHOLDERS[1], html.escape(target))
    return page.replace("<head>", "<head>\n  " + MARKER, 1)


def wanted(row, types):
    if types and row["type"] not in types:
        return False
    if row["action"] == "redirect":
        return True
    # Feed aliases point at index.xml files, which Hugo aliases can't do.
    return row["action"] == "alias" and row["type"] == "feed"


def content_paths():
    """URLs Hugo renders from content/: posts (/slug/), root pages (/name/), terms, and their aliases."""
    paths = set()
    for f in CONTENT.rglob("*.md"):
        text = f.read_text(encoding="utf-8")
        front = text.split("---", 2)[1] if text.startswith("---") else ""
        slug = re.search(r"^slug:\s*['\"]?([^'\"\n]+)", front, re.M)
        rel = f.relative_to(CONTENT).parts
        name = slug.group(1).strip() if slug else (rel[-2] if f.name == "_index.md" else f.stem)
        if rel[0] == "categories" and len(rel) > 2:
            paths.add(f"/category/{name}/")
        elif rel[0] == "tags" and len(rel) > 2:
            paths.add(f"/tag/{name}/")
        elif f.name != "_index.md":
            paths.add(f"/{name}/")
        block = re.search(r"^aliases:\n((?:- .*\n)+)", front, re.M)
        if block:
            paths.update(a[2:].strip().strip("'\"") for a in block.group(1).splitlines())
    return paths


def main(argv):
    check = "--check" in argv
    types = set()
    if "--types" in argv:
        types = set(argv[argv.index("--types") + 1].split(","))
    with INVENTORY.open(encoding="utf-8") as f:
        inventory = list(csv.DictReader(f))
    type_of = {r["old_url"]: r["type"] for r in inventory}
    rows = [r for r in inventory if wanted(r, types)]

    # Paths Hugo renders itself: kept pages and old-slug aliases from the inventory, plus every page
    # and alias in content/ (which also covers posts added after the WordPress export).
    hugo_paths = {r["old_url"] for r in inventory
                  if r["action"] == "keep" or (r["action"] == "alias" and r["type"] != "feed")}
    hugo_paths |= content_paths()
    clash = sorted(r["old_url"] for r in rows if r["old_url"] in hugo_paths)
    if clash:
        sys.exit("redirect pages would collide with pages Hugo renders: " + ", ".join(clash))

    expected = {}
    for r in rows:
        old = r["old_url"]
        if "?" in old or not old.endswith("/"):
            sys.exit(f"cannot make a static page for {old}")
        expected[STATIC / old.strip("/") / "index.html"] = render(r["target"])

    # Pages generated earlier (for the types handled in this run) that are no longer wanted.
    stale = []
    for f in STATIC.rglob("index.html"):
        if f in expected or MARKER not in f.read_text(encoding="utf-8", errors="replace")[:400]:
            continue
        row_type = type_of.get("/" + f.parent.relative_to(STATIC).as_posix() + "/")
        if types and row_type and row_type not in types:
            continue
        stale.append(f)

    if check:
        missing = [p for p, page in expected.items() if not p.exists()]
        changed = [p for p, page in expected.items() if p.exists() and p.read_text(encoding="utf-8") != page]
        for label, files in (("missing", missing), ("out of date", changed), ("stale", stale)):
            for p in files[:20]:
                print(f"{label}: {p.relative_to(ROOT)}")
        if missing or changed or stale:
            sys.exit(f"redirect pages differ from the inventory ({len(missing)} missing, {len(changed)} out of "
                     f"date, {len(stale)} stale): run python3 -I scripts/make_redirects.py and commit")
        print(f"OK: {len(expected)} redirect pages match the inventory")
        return

    for p, page in expected.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(page, encoding="utf-8")
    for f in stale:
        f.unlink()
        for d in f.parents:
            if d == STATIC or any(d.iterdir()):
                break
            d.rmdir()
    print(f"{len(expected)} redirect pages written under static/" + (f", {len(stale)} stale removed" if stale else ""))


if __name__ == "__main__":
    main(sys.argv[1:])

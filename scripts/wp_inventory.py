#!/usr/bin/env python3
"""Phase 1: build migration/url-inventory.csv from a WordPress WXR export.

Usage: python3 scripts/wp_inventory.py source/<export>.xml migration/url-inventory.csv

Columns: old_url, type, title, description, date, action, target, note
  action = keep      URL is generated by Hugo at the same path
           alias     Hugo `aliases:` front matter on the target page
           redirect  static redirect page generated in Phase 4
"""
import csv
import html
import math
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from urllib.parse import urlparse

NS = {
    "wp": "http://wordpress.org/export/1.2/",
    "content": "http://purl.org/rss/1.0/modules/content/",
    "dc": "http://purl.org/dc/elements/1.1/",
}
SITE = "https://monicaespinel.com"
HOME_DESCRIPTION = (
    "Monica Espinel is a curator and writer specialized in Contemporary Art from "
    "Latin America. She is currently a Ph.D. candidate at The Graduate Center, "
    "City University of New York."
)
# Posts per page is not in the export. Confirmed on the live site: the author archive
# /author/monica-espinel/ shows 8 posts and its last page is /page/5/ (33 posts / 8).
PER_PAGE = 8
PAGE_MARGIN = 0  # extra redirect pages beyond the last computed page


def t(el, path):
    return html.unescape((el.findtext(path, namespaces=NS) or "").strip())


def meta(item):
    out = defaultdict(list)
    for m in item.findall("wp:postmeta", NS):
        out[t(m, "wp:meta_key")].append(t(m, "wp:meta_value"))
    return out


def description(m):
    for key in ("_aioseo_description", "_aioseop_description"):
        for v in m.get(key, []):
            if v and "#" not in v[:1]:  # skip AIOSEO tag placeholders like #post_excerpt
                return re.sub(r"\s+", " ", html.unescape(v)).strip()
    return ""


def path_of(url):
    p = urlparse(url)
    path = p.path or "/"
    if p.query:
        path += "?" + p.query
    return path


def nicename(login):
    # WordPress user_nicename = sanitize_title(user_login): lowercase, '.'/'_' -> '-'
    return re.sub(r"[^a-z0-9-]+", "-", login.lower()).strip("-")


def main(src, dst):
    ch = ET.parse(src).getroot().find("channel")
    items = ch.findall("item")
    by_id = {t(i, "wp:post_id"): i for i in items}
    rows = []

    def add(old_url, typ, title="", desc="", date="", action="keep", target="", note=""):
        rows.append(dict(old_url=old_url, type=typ, title=title, description=desc,
                         date=date, action=action, target=target or old_url, note=note))

    authors = {t(a, "wp:author_login"): t(a, "wp:author_display_name")
               for a in ch.findall("wp:author", NS)}

    add("/", "home", t(ch, "title"), HOME_DESCRIPTION)
    add("/feed/", "feed", "Main RSS feed", action="alias", target="/index.xml")
    add("/comments/feed/", "feed", "Comments feed", action="redirect", target="/index.xml",
        note="no comments in export")

    posts = []
    cat_posts, tag_posts, author_posts = defaultdict(list), defaultdict(list), defaultdict(list)
    for i in items:
        typ, status = t(i, "wp:post_type"), t(i, "wp:status")
        if typ not in ("post", "page") or status != "publish":
            continue
        m = meta(i)
        slug = t(i, "wp:post_name")
        url = path_of(t(i, "link"))
        date = t(i, "wp:post_date")[:10]
        desc = description(m)
        note = "" if desc else "TODO: no description in export"
        add(url, typ, t(i, "title"), desc, date, note=note)
        for old in sorted(set(m.get("_wp_old_slug", []))):
            if old and old != slug:
                add(f"/{old}/", typ, t(i, "title"), desc, date, "alias", url, "old slug")
        if typ == "post":
            posts.append(i)
            author_posts[t(i, "dc:creator")].append(i)
            for c in i.findall("category"):
                if c.get("domain") == "category":
                    cat_posts[c.get("nicename")].append(i)
                elif c.get("domain") == "post_tag":
                    tag_posts[c.get("nicename")].append(i)

    def pagination(base, count, title, target, note=""):
        last = math.ceil(count / PER_PAGE)
        for n in range(2, last + PAGE_MARGIN + 1):
            extra = "; margin page" if n > last else ""
            add(f"{base}page/{n}/", "pagination", f"{title} – page {n}", action="redirect",
                target=target, note=f"{PER_PAGE} posts per page{extra}{note}")

    pagination("/", len(posts), "Home", "/")

    for c in ch.findall("wp:category", NS):
        slug, name = t(c, "wp:category_nicename"), t(c, "wp:cat_name")
        n = len(cat_posts.get(slug, []))
        base = f"/category/{slug}/"
        if n:
            add(base, "category", name, t(c, "wp:category_description"))
            pagination(base, n, name, base)
            add(f"{base}feed/", "feed", f"{name} feed", action="alias", target=f"{base}index.xml")
        else:
            add(base, "category", name, action="redirect", target="/", note="no published posts")

    for tg in ch.findall("wp:tag", NS):
        slug, name = t(tg, "wp:tag_slug"), t(tg, "wp:tag_name")
        n = len(tag_posts.get(slug, []))
        base = f"/tag/{slug}/"
        if n:
            add(base, "tag", name, t(tg, "wp:tag_description"))
            pagination(base, n, name, base)
            add(f"{base}feed/", "feed", f"{name} feed", action="alias", target=f"{base}index.xml")
        else:
            add(base, "tag", name, action="redirect", target="/", note="no published posts")

    for login, plist in sorted(author_posts.items()):
        base = f"/author/{nicename(login)}/"
        name = authors.get(login, login)
        note = "author slug confirmed on live site (/author/monica-espinel/); same rule for all"
        add(base, "author", name, action="redirect", target="/", note=note)
        pagination(base, len(plist), name, "/")
        add(f"{base}feed/", "feed", f"{name} feed", action="redirect", target="/index.xml")

    # Date archives (/YYYY/, /YYYY/MM/) exist on every WordPress site.
    years, months = set(), set()
    for p in posts:
        d = t(p, "wp:post_date")
        years.add(d[:4]); months.add(d[:7])
    for y in sorted(years):
        add(f"/{y}/", "date", f"Archive {y}", action="redirect", target="/")
    for ym in sorted(months):
        y, mo = ym.split("-")
        add(f"/{y}/{mo}/", "date", f"Archive {ym}", action="redirect", target="/")

    # Attachment pages -> parent post if published, else home.
    for i in items:
        if t(i, "wp:post_type") != "attachment":
            continue
        url = path_of(t(i, "link"))
        parent = by_id.get(t(i, "wp:post_parent"))
        if parent is not None and t(parent, "wp:status") == "publish" \
                and t(parent, "wp:post_type") in ("post", "page"):
            target, note = path_of(t(parent, "link")), ""
        else:
            target, note = "/", "parent missing or unpublished"
        if "?" in url:
            note = "query-string URL: cannot be served on GitHub Pages; " + note
            action = "unsupported"
        else:
            action = "redirect"
        add(url, "attachment", t(i, "title"), date=t(i, "wp:post_date")[:10],
            action=action, target=target, note=note.strip("; "))
        # Renamed attachments: WordPress serves the old name under the same parent path.
        base = url.rsplit("/", 2)[0] + "/" if "?" not in url else "/"
        for old in sorted(set(meta(i).get("_wp_old_slug", []))):
            if old and old != t(i, "wp:post_name"):
                add(f"{base}{old}/", "attachment", t(i, "title"), date=t(i, "wp:post_date")[:10],
                    action="redirect", target=target,
                    note="old attachment slug; path derived from current attachment URL")

    seen, unique = set(), []
    for r in rows:
        if r["old_url"] not in seen:
            seen.add(r["old_url"]); unique.append(r)
        else:
            print(f"duplicate URL skipped: {r['old_url']} ({r['type']})", file=sys.stderr)

    with open(dst, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(unique[0].keys()))
        w.writeheader(); w.writerows(unique)

    summary = defaultdict(lambda: defaultdict(int))
    for r in unique:
        summary[r["type"]][r["action"]] += 1
    print(f"{len(unique)} URLs written to {dst}")
    for typ, acts in summary.items():
        print(f"  {typ:11} " + ", ".join(f"{a}={n}" for a, n in sorted(acts.items())))


if __name__ == "__main__":
    main(*sys.argv[1:3])
